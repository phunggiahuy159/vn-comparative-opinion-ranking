#!/usr/bin/env bash
# Bundle project files into one Kaggle GPU script-kernel and push (= run) it.
# Usage: kaggle/push.sh <slug> "<command run from project root>" "<pip pkgs>" <file> [file ...]
#   kaggle/push.sh vabsa-suite "python src/run_suite.py configs/absa_suite.json" "pyvi" \
#       src/absa_transformer.py src/run_suite.py configs/absa_suite.json
# Monitor:  kaggle kernels status <user>/<slug>
# Fetch:    kaggle kernels output <user>/<slug> -p kaggle/out/<slug>
set -euo pipefail
cd "$(dirname "$0")/.."
SLUG=$1; CMD=$2; PIP=$3; shift 3
USER_NAME=$(kaggle config view 2>/dev/null | awk -F': ' '/username/{print $2}' | tr -d ' ')
[ -z "$USER_NAME" ] && { echo "Not logged in: run 'kaggle auth login'"; exit 1; }
DIR=kaggle/build/$SLUG; rm -rf "$DIR"; mkdir -p "$DIR"
# GPU=0 → CPU kernel (starts immediately; Kaggle GPU queue is often full)
if [ "${GPU:-1}" = "0" ]; then GPU_JSON=false; ACC_ARGS=(); else GPU_JSON=true; ACC_ARGS=(--accelerator "${ACCEL:-NvidiaTeslaT4}"); fi

python3 - "$DIR/run.py" "$CMD" "$PIP" "$@" <<'EOF'
import base64, json, sys
out, cmd, pip, files = sys.argv[1], sys.argv[2], sys.argv[3].split(), sys.argv[4:]
blob = {f: base64.b64encode(open(f, "rb").read()).decode() for f in files}
src = f'''# Auto-generated by kaggle/push.sh — edit the project files, not this.
import base64, os, subprocess, sys, pathlib
PROJ = pathlib.Path("/kaggle/working/proj")
FILES = {json.dumps(blob)}
for name, b in FILES.items():
    p = PROJ / name; p.parent.mkdir(parents=True, exist_ok=True); p.write_bytes(base64.b64decode(b))
PIP = {json.dumps(pip)}
if PIP:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", *PIP], check=True)
os.environ["TOKENIZERS_PARALLELISM"] = "false"
subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv || nproc", shell=True)
rc = subprocess.run({json.dumps(cmd)}, shell=True, cwd=PROJ).returncode
# drop the source copy, keep results/ as kernel output
for name in FILES:
    (PROJ / name).unlink(missing_ok=True)
sys.exit(rc)
'''
open(out, "w").write(src)
EOF

cat > "$DIR/kernel-metadata.json" <<EOF
{
  "id": "$USER_NAME/$SLUG",
  "title": "$SLUG",
  "code_file": "run.py",
  "language": "python",
  "kernel_type": "script",
  "is_private": true,
  "enable_gpu": ${GPU_JSON},
  "enable_internet": true,
  "dataset_sources": [],
  "competition_sources": [],
  "kernel_sources": []
}
EOF
python3 -c "import ast; ast.parse(open('$DIR/run.py').read())"
OUT=$(kaggle kernels push -p "$DIR" ${ACC_ARGS[@]+"${ACC_ARGS[@]}"} 2>&1); echo "$OUT"
echo "$OUT" | grep -q "successfully pushed" || { echo "PUSH FAILED: $USER_NAME/$SLUG"; exit 1; }
echo "pushed $USER_NAME/$SLUG"
